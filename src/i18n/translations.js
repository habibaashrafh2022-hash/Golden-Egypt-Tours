// ── Dot-path lookup helper, e.g. t("common.nav.home") ──────────
export function getTranslation(language, path) {
  const dig = (obj) => path.split(".").reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), obj);
  const fromLang = dig(translations[language]);
  if (fromLang !== undefined) return fromLang;
  const fromEnglish = dig(translations.en);
  if (fromEnglish !== undefined) return fromEnglish;
  return path; // last-resort: show the key itself so missing translations are obvious, not blank
}